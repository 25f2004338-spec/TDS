class VerifyRequest(BaseModel):
    token: str


@app.post("/verify")
def verify_token(request: VerifyRequest):
    try:
        claims = jwt.decode(
            request.token,
            PUBLIC_KEY,
            algorithms=["RS256"],
            issuer=ISSUER,
            audience=AUDIENCE,
            options={"require": ["exp", "iss", "aud", "sub"]},
        )

        if not claims.get("email"):
            raise jwt.InvalidTokenError("Missing email claim")

        return {
            "valid": True,
            "email": claims["email"],
            "sub": claims["sub"],
            "aud": claims["aud"],
        }

    except jwt.PyJWTError as exc:
        logging.warning("JWT verification rejected: %s", type(exc).__name__)
        raise HTTPException(
            status_code=401,
            detail={"valid": False},
        )
